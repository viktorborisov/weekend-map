def yandex_map_url(lat, lon, name):
    import urllib.parse
    return f'https://yandex.ru/maps/?ll={lon}%2C{lat}&z=15&text={urllib.parse.quote(name)}'


def download_yandex_photo(lat, lon, osm_id):
    media_dir = os.path.join(settings.MEDIA_ROOT, 'places')
    os.makedirs(media_dir, exist_ok=True)
    filepath = os.path.join(media_dir, f'{osm_id}.jpg')

    if os.path.exists(filepath):
        return f'/media/places/{osm_id}.jpg'

    for z in [16, 15, 14]:
        url = (
            f'https://static-maps.yandex.ru/1.x/'
            f'?ll={lon},{lat}&size=600,400&z={z}&l=sat'
            f'&pt={lon},{lat},pm2rdm'
        )
        try:
            resp = requests.get(url, timeout=30, headers={'User-Agent': 'weekend-map/1.0'})
            if resp.status_code == 200 and len(resp.content) > 1000:
                with open(filepath, 'wb') as f:
                    f.write(resp.content)
                return f'/media/places/{osm_id}.jpg'
        except Exception:
            pass
        time.sleep(0.5)

    return ''


