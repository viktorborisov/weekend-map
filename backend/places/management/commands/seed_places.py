class Command(BaseCommand):
    help = 'Seed the database with curated weekend trip places in Leningrad Oblast'

    def handle(self, *args, **options):
        CachedPlace.objects.all().delete()
        self.stdout.write(self.style.SUCCESS('Cleared existing places'))

        for place in SEED_PLACES:
            osm_id = place['osm_id']
            lat = place['lat']
            lon = place['lon']
            name = place['name']

            photo_path = download_yandex_photo(lat, lon, osm_id)
            if photo_path:
                place['photo_url'] = photo_path
            else:
                place['photo_url'] = ''

            tags = place.get('tags', {})
            tags['yandex_map_url'] = yandex_map_url(lat, lon, name)
            place['tags'] = tags

            obj = CachedPlace.objects.create(
                osm_id=osm_id,
                name=name,
                category=place['category'],
                lat=lat,
                lon=lon,
                description=place['description'],
                tags=tags,
                photo_url=place.get('photo_url', ''),
            )
            self.stdout.write(f'  Created: {name} (photo: {"yes" if photo_path else "no"})')

        self.stdout.write(
            self.style.SUCCESS(f'Seeded {len(SEED_PLACES)} places')
        )
